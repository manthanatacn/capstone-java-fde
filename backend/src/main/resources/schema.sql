-- HealthDekho current-scope schema (FR-1 .. FR-5), applied by Spring Boot SQL init on startup.
-- Every statement is idempotent so the app can restart against an existing database.
-- Money: NUMERIC(19,2). Dates: DATE. Audit timestamps: TIMESTAMPTZ. Ids: BIGINT identity.
-- Claim tables (FE-1) are intentionally not created here.

create table if not exists customer (
    customer_id     bigint generated by default as identity primary key,
    email           varchar(150) not null,
    password_hash   varchar(100) not null,
    full_name       varchar(120) not null,
    date_of_birth   date         not null,
    phone           varchar(15)  not null,
    status          varchar(20)  not null default 'ACTIVE',
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    constraint uq_customer_email unique (email),
    constraint ck_customer_dob_not_future check (date_of_birth <= current_date),
    constraint ck_customer_status check (status in ('ACTIVE', 'INACTIVE'))
);
create index if not exists ix_customer_status on customer (status);
create index if not exists ix_customer_name_lower on customer (lower(full_name));

-- Back-office users (operations desk). Not part of the spec's table list; added so that
-- FR-4/FR-5 "search any customer's policy" has a legitimate actor. See architecture ADR-2.
create table if not exists staff_user (
    staff_id        bigint generated by default as identity primary key,
    email           varchar(150) not null,
    password_hash   varchar(100) not null,
    full_name       varchar(120) not null,
    active          boolean      not null default true,
    created_at      timestamptz  not null default now(),
    constraint uq_staff_email unique (email)
);

create table if not exists insurance_product (
    product_id          bigint generated by default as identity primary key,
    product_code        varchar(30)   not null,
    policy_name         varchar(120)  not null,
    policy_type         varchar(20)   not null,
    description         varchar(500),
    term_months         integer       not null,
    premium_frequency   varchar(20)   not null,
    premium_amount      numeric(19,2) not null,
    sum_insured         numeric(19,2) not null,
    min_entry_age       integer       not null,
    max_entry_age       integer       not null,
    active              boolean       not null default true,
    created_at          timestamptz   not null default now(),
    constraint uq_product_code unique (product_code),
    constraint ck_product_type check (policy_type in ('TERM', 'HEALTH', 'SAVINGS', 'RETIREMENT')),
    constraint ck_product_frequency check (premium_frequency in ('MONTHLY', 'QUARTERLY', 'HALF_YEARLY', 'YEARLY')),
    constraint ck_product_premium_positive check (premium_amount > 0),
    constraint ck_product_sum_insured_positive check (sum_insured > 0),
    constraint ck_product_term_positive check (term_months > 0),
    constraint ck_product_entry_age check (min_entry_age >= 0 and max_entry_age >= min_entry_age),
    -- the term must split into whole installments
    constraint ck_product_term_fits_frequency check (
        term_months % case premium_frequency
                          when 'MONTHLY' then 1
                          when 'QUARTERLY' then 3
                          when 'HALF_YEARLY' then 6
                          when 'YEARLY' then 12
                      end = 0)
);
create index if not exists ix_product_active on insurance_product (active);

create sequence if not exists policy_number_seq start with 1;

create table if not exists customer_policy (
    policy_id               bigint generated by default as identity primary key,
    policy_number           varchar(20)   not null,
    customer_id             bigint        not null references customer (customer_id),
    product_id              bigint        not null references insurance_product (product_id),
    start_date              date          not null,
    maturity_date           date          not null,
    -- contracted values, frozen at registration (product master may change later)
    premium_frequency       varchar(20)   not null,
    premium_amount          numeric(19,2) not null,
    sum_insured             numeric(19,2) not null,
    total_premium_payable   numeric(19,2) not null,
    -- state of cover; MATURED is reported once the maturity date has passed (architecture §4)
    status                  varchar(20)   not null default 'ACTIVE',
    -- set when the last installment is paid; "fully paid" is not a policy status (PRD A-6)
    fully_paid_on           date,
    created_at              timestamptz   not null default now(),
    updated_at              timestamptz   not null default now(),
    constraint uq_policy_number unique (policy_number),
    -- duplicate-registration rule: one policy per customer per product
    constraint uq_policy_customer_product unique (customer_id, product_id),
    constraint ck_policy_dates check (maturity_date > start_date),
    constraint ck_policy_amounts check (premium_amount > 0 and sum_insured > 0 and total_premium_payable > 0),
    constraint ck_policy_status check (status in ('ACTIVE', 'MATURED')),
    constraint ck_policy_fully_paid_on check (fully_paid_on is null or fully_paid_on >= start_date)
);
create index if not exists ix_policy_customer on customer_policy (customer_id);
create index if not exists ix_policy_status on customer_policy (status);

create table if not exists premium_installment (
    installment_id          bigint generated by default as identity primary key,
    policy_id               bigint        not null references customer_policy (policy_id),
    installment_number      integer       not null,
    due_date                date          not null,
    grace_period_end_date   date          not null,
    scheduled_amount        numeric(19,2) not null,
    penalty_amount          numeric(19,2) not null default 0,
    paid_amount             numeric(19,2) not null default 0,
    payment_status          varchar(20)   not null default 'PENDING',
    version                 bigint        not null default 0,
    constraint uq_installment_policy_number unique (policy_id, installment_number),
    constraint ck_installment_number_positive check (installment_number > 0),
    constraint ck_installment_grace check (grace_period_end_date > due_date),
    constraint ck_installment_amounts check (scheduled_amount > 0 and penalty_amount >= 0),
    constraint ck_installment_paid_amount check (paid_amount between 0 and scheduled_amount + penalty_amount),
    constraint ck_installment_status check (payment_status in ('PENDING', 'PARTIALLY_PAID', 'PAID', 'OVERDUE'))
);
create index if not exists ix_installment_policy on premium_installment (policy_id);
create index if not exists ix_installment_due_date on premium_installment (due_date);

create sequence if not exists transaction_ref_seq start with 1;

-- Immutable payment ledger: rows are inserted, never updated.
create table if not exists premium_payment (
    payment_id              bigint generated by default as identity primary key,
    installment_id          bigint        not null references premium_installment (installment_id),
    transaction_reference   varchar(30)   not null,
    payment_date            date          not null,
    amount_paid             numeric(19,2) not null,
    penalty_amount          numeric(19,2) not null default 0,
    payment_method          varchar(20)   not null,
    created_at              timestamptz   not null default now(),
    constraint uq_payment_txn_ref unique (transaction_reference),
    constraint ck_payment_amount_positive check (amount_paid > 0),
    constraint ck_payment_penalty check (penalty_amount >= 0),
    constraint ck_payment_method check (payment_method in ('UPI', 'NET_BANKING', 'CARD', 'CASH', 'CHEQUE'))
);
create index if not exists ix_payment_installment on premium_payment (installment_id);
create index if not exists ix_payment_date on premium_payment (payment_date);

create table if not exists ai_recommendation_request (
    recommendation_request_id   bigint generated by default as identity primary key,
    customer_id                 bigint       not null references customer (customer_id),
    insurance_goals             varchar(500),
    preferred_term              varchar(20),
    preferred_policy_type       varchar(20),
    calculated_age              integer      not null,
    generation_source           varchar(20)  not null,
    model_name                  varchar(100) not null,
    model_version               varchar(100),
    prompt_version              varchar(20)  not null,
    prompt_text                 text,
    requested_at                timestamptz  not null default now(),
    constraint ck_rec_source check (generation_source in ('MODEL', 'RULE_BASED'))
);
create index if not exists ix_rec_request_customer on ai_recommendation_request (customer_id);
create index if not exists ix_rec_request_requested_at on ai_recommendation_request (requested_at);

create table if not exists ai_recommendation_item (
    recommendation_item_id      bigint generated by default as identity primary key,
    recommendation_request_id   bigint       not null references ai_recommendation_request (recommendation_request_id),
    product_id                  bigint       not null references insurance_product (product_id),
    rank_order                  integer      not null,
    recommendation_reason       varchar(1000) not null,
    suitability                 varchar(10)  not null,
    selected_for_registration   boolean      not null default false,
    constraint uq_rec_item_request_product unique (recommendation_request_id, product_id),
    constraint ck_rec_item_rank check (rank_order > 0),
    constraint ck_rec_item_suitability check (suitability in ('HIGH', 'MEDIUM', 'LOW'))
);
create index if not exists ix_rec_item_request on ai_recommendation_item (recommendation_request_id);
